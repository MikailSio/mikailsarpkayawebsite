/* ── 10. Inference ───────────────────────────────────────── */
+ '<h3 class="l-section-title">Adım 10 — Yeni Metin Üzerinde Inference</h3>'
+ '<p class="l-text">Inference için iki yaklaşım: üst düzey <code>pipeline</code> API\'si (kurulumu en hızlı) ve manuel tahmin fonksiyonu (ham logit\'leri, olasılıkları ve toplu işlem üzerinde tam kontrolü sağlar).</p>'

+ '<div class="code-wrap"><div class="code-label"><span>PYTHON (DEMO)</span> Inference &mdash; Pipeline and Manual Predict <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="kw">import</span> torch\n'
+ '<span class="kw">import</span> torch.nn.functional <span class="kw">as</span> F\n'
+ '<span class="kw">from</span> transformers <span class="kw">import</span> pipeline\n'
+ '\n'
+ '<span class="cm"># ── Option A: pipeline — simplest possible inference ─────────</span>\n'
+ 'classifier = <span class="fn">pipeline</span>(\n'
+ '    task=<span class="str">"text-classification"</span>,\n'
+ '    model=SAVE_DIR,\n'
+ '    tokenizer=SAVE_DIR,\n'
+ '    device=<span class="num">0</span> <span class="kw">if</span> torch.cuda.<span class="fn">is_available</span>() <span class="kw">else</span> -<span class="num">1</span>,  <span class="cm"># 0=GPU, -1=CPU</span>\n'
+ '    truncation=<span class="kw">True</span>,\n'
+ '    max_length=<span class="num">512</span>,\n'
+ ')\n'
+ '\n'
+ 'results = <span class="fn">classifier</span>([\n'
+ '    <span class="str">"This film is a masterpiece. Best movie I\'ve seen in years."</span>,\n'
+ '    <span class="str">"A complete waste of time. The plot makes no sense whatsoever."</span>,\n'
+ '    <span class="str">"It was okay. Not bad, not great — just average."</span>,\n'
+ '])\n'
+ '<span class="kw">for</span> r <span class="kw">in</span> results:\n'
+ '    <span class="fn">print</span>(<span class="str">f"  {r[\'label\']:8s}  score={r[\'score\']:.4f}"</span>)\n'
+ '<span class="cm"># POSITIVE  score=0.9987</span>\n'
+ '<span class="cm"># NEGATIVE  score=0.9964</span>\n'
+ '<span class="cm"># NEGATIVE  score=0.7231  ← uncertain review</span>\n'
+ '\n'
+ '\n'
+ '<span class="cm"># ── Option B: Manual predict function (full control) ─────────</span>\n'
+ '<span class="kw">def</span> <span class="fn">predict_sentiment</span>(texts, model, tokenizer, device, batch_size=<span class="num">32</span>):\n'
+ '    <span class="str">"""</span>\n'
+ '    Run inference on a list of texts.\n'
+ '    Returns: labels (list of str), probabilities (numpy array)\n'
+ '    <span class="str">"""</span>\n'
+ '    model.<span class="fn">eval</span>()\n'
+ '    all_probs = []\n'
+ '\n'
+ '    <span class="kw">for</span> i <span class="kw">in</span> <span class="fn">range</span>(<span class="num">0</span>, <span class="fn">len</span>(texts), batch_size):\n'
+ '        batch_texts = texts[i : i + batch_size]\n'
+ '\n'
+ '<span class="cm">        # Tokenize the batch</span>\n'
+ '        encoded = <span class="fn">tokenizer</span>(\n'
+ '            batch_texts,\n'
+ '            padding=<span class="kw">True</span>,\n'
+ '            truncation=<span class="kw">True</span>,\n'
+ '            max_length=<span class="num">512</span>,\n'
+ '            return_tensors=<span class="str">"pt"</span>,   <span class="cm"># Return PyTorch tensors</span>\n'
+ '        ).<span class="fn">to</span>(device)\n'
+ '\n'
+ '        <span class="kw">with</span> torch.<span class="fn">no_grad</span>():\n'
+ '            outputs = <span class="fn">model</span>(**encoded)\n'
+ '<span class="cm">        # outputs.logits shape: (batch_size, 2)</span>\n'
+ '        probs = F.<span class="fn">softmax</span>(outputs.logits, dim=-<span class="num">1</span>)  <span class="cm"># Convert to probabilities</span>\n'
+ '        all_probs.<span class="fn">append</span>(probs.<span class="fn">cpu</span>().<span class="fn">numpy</span>())\n'
+ '\n'
+ '    all_probs = np.<span class="fn">vstack</span>(all_probs)      <span class="cm"># shape: (N, 2)</span>\n'
+ '    pred_ids  = np.<span class="fn">argmax</span>(all_probs, axis=<span class="num">1</span>)\n'
+ '    pred_labels = [id2label[i] <span class="kw">for</span> i <span class="kw">in</span> pred_ids]\n'
+ '\n'
+ '    <span class="kw">return</span> pred_labels, all_probs\n'
+ '\n'
+ '\n'
+ 'texts = [\n'
+ '    <span class="str">"Absolutely brilliant. One of the greatest films ever made."</span>,\n'
+ '    <span class="str">"I fell asleep halfway through. Completely boring."</span>,\n'
+ '    <span class="str">"The acting was great but the story was confusing."</span>,\n'
+ ']\n'
+ '\n'
+ 'labels, probs = <span class="fn">predict_sentiment</span>(texts, model, tokenizer, device)\n'
+ '<span class="kw">for</span> text, label, prob <span class="kw">in</span> <span class="fn">zip</span>(texts, labels, probs):\n'
+ '    <span class="fn">print</span>(<span class="str">f"  [{label}] neg={prob[0]:.3f} pos={prob[1]:.3f}"</span>)\n'
+ '    <span class="fn">print</span>(<span class="str">f"  Text: {text[:60]}..."</span>)\n'
+ '<span class="cm">#   [POSITIVE] neg=0.002 pos=0.998</span>\n'
+ '<span class="cm">#   [NEGATIVE] neg=0.981 pos=0.019</span>\n'
+ '<span class="cm">#   [POSITIVE] neg=0.231 pos=0.769  ← mixed sentiment, less confident</span>\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>Bu parçada karşılaştırılan iki inference yolu:</strong> 1) <strong>A Seçeneği — pipeline:</strong> <code>pipeline(task="text-classification", model=SAVE_DIR, tokenizer=SAVE_DIR, device=0 if torch.cuda.is_available() else -1, truncation=True, max_length=512)</code> tokenizasyonu, GPU yerleşimini ve son işlemeyi tek bir çağrılabilir nesnede paketler; sonuç <code>[{"label": ..., "score": ...}, ...]</code> olarak döner. 2) <strong>B Seçeneği — manuel <code>predict_sentiment(...)</code>:</strong> <code>padding=True, truncation=True, max_length=512, return_tensors="pt"</code> ile batch hâlinde tokenize eder, <code>torch.no_grad()</code> altında <code>model(**encoded)</code> çalıştırır ve ardından <code>F.softmax(outputs.logits, dim=-1)</code> uygular. 3) Manuel mod, downstream eşikleme, kalibrasyon veya belirsizlik tahmini için ham olasılıkları (<code>neg=0.002 pos=0.998</code>) saklamanıza izin verir — üçüncü "karışık duygu" yorumunun yazdırılan çıktısında görülebilir.</p>'

