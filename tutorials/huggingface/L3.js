+ '<h4 class="l-subsection-title">6a — DataLoader, Optimizer ve Zamanlayıcı Kurulumu</h4>'
+ '<div class="code-wrap"><div class="code-label"><span>PYTHON (DEMO)</span> DataLoader, Optimizer, Scheduler Setup <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="kw">import</span> torch\n'
+ '<span class="kw">from</span> torch.utils.data <span class="kw">import</span> DataLoader\n'
+ '<span class="kw">from</span> torch.optim <span class="kw">import</span> AdamW\n'
+ '<span class="kw">from</span> transformers <span class="kw">import</span> get_linear_schedule_with_warmup, DataCollatorWithPadding\n'
+ '<span class="kw">from</span> tqdm.auto <span class="kw">import</span> tqdm\n'
+ '\n'
+ '<span class="cm"># ── DataLoaders ──────────────────────────────────────────────</span>\n'
+ 'data_collator = <span class="fn">DataCollatorWithPadding</span>(tokenizer=tokenizer)\n'
+ '\n'
+ 'train_loader = <span class="fn">DataLoader</span>(\n'
+ '    tokenized_datasets[<span class="str">"train"</span>],\n'
+ '    batch_size=<span class="num">16</span>,\n'
+ '    shuffle=<span class="kw">True</span>,          <span class="cm"># Always shuffle training data!</span>\n'
+ '    collate_fn=data_collator,\n'
+ '    num_workers=<span class="num">4</span>,\n'
+ '    pin_memory=<span class="kw">True</span>,       <span class="cm"># Faster GPU transfer</span>\n'
+ ')\n'
+ '\n'
+ 'val_loader = <span class="fn">DataLoader</span>(\n'
+ '    tokenized_datasets[<span class="str">"validation"</span>],\n'
+ '    batch_size=<span class="num">32</span>,\n'
+ '    shuffle=<span class="kw">False</span>,         <span class="cm"># Never shuffle evaluation data</span>\n'
+ '    collate_fn=data_collator,\n'
+ '    num_workers=<span class="num">4</span>,\n'
+ '    pin_memory=<span class="kw">True</span>,\n'
+ ')\n'
+ '\n'
+ '<span class="cm"># ── Optimizer ────────────────────────────────────────────────</span>\n'
+ '<span class="cm"># AdamW: Adam with decoupled weight decay (Loshchilov & Hutter, 2019)</span>\n'
+ '<span class="cm"># Critical: separate parameters that should NOT have weight decay</span>\n'
+ 'no_decay = [<span class="str">"bias"</span>, <span class="str">"LayerNorm.weight"</span>]\n'
+ 'optimizer_grouped_parameters = [\n'
+ '    {\n'
+ '        <span class="str">"params"</span>: [p <span class="kw">for</span> n, p <span class="kw">in</span> model.<span class="fn">named_parameters</span>()\n'
+ '                   <span class="kw">if</span> <span class="kw">not</span> <span class="fn">any</span>(nd <span class="kw">in</span> n <span class="kw">for</span> nd <span class="kw">in</span> no_decay)],\n'
+ '        <span class="str">"weight_decay"</span>: <span class="num">0.01</span>,\n'
+ '    },\n'
+ '    {\n'
+ '        <span class="str">"params"</span>: [p <span class="kw">for</span> n, p <span class="kw">in</span> model.<span class="fn">named_parameters</span>()\n'
+ '                   <span class="kw">if</span> <span class="fn">any</span>(nd <span class="kw">in</span> n <span class="kw">for</span> nd <span class="kw">in</span> no_decay)],\n'
+ '        <span class="str">"weight_decay"</span>: <span class="num">0.0</span>,   <span class="cm"># No decay on biases and LayerNorm</span>\n'
+ '    },\n'
+ ']\n'
+ 'optimizer = <span class="fn">AdamW</span>(optimizer_grouped_parameters, lr=<span class="num">2e-5</span>)\n'
+ '\n'
+ '<span class="cm"># ── Learning rate scheduler ──────────────────────────────────</span>\n'
+ 'NUM_EPOCHS = <span class="num">3</span>\n'
+ 'GRADIENT_ACCUMULATION_STEPS = <span class="num">2</span>\n'
+ 'num_training_steps = (<span class="fn">len</span>(train_loader) // GRADIENT_ACCUMULATION_STEPS) * NUM_EPOCHS\n'
+ 'num_warmup_steps   = <span class="fn">int</span>(<span class="num">0.06</span> * num_training_steps)   <span class="cm"># 6% warmup</span>\n'
+ '\n'
+ 'scheduler = <span class="fn">get_linear_schedule_with_warmup</span>(\n'
+ '    optimizer,\n'
+ '    num_warmup_steps=num_warmup_steps,\n'
+ '    num_training_steps=num_training_steps,\n'
+ ')\n'
+ '\n'
+ 'model.<span class="fn">to</span>(device)\n'
+ '<span class="fn">print</span>(<span class="str">f"Training steps: {num_training_steps}, Warmup steps: {num_warmup_steps}"</span>)\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>Optimizer ve scheduler\'ın elle nasıl kurulduğu:</strong> 1) <code>no_decay</code> listesi (<code>["bias", "LayerNorm.weight"]</code>) parametreleri iki gruba böler; böylece weight decay yalnızca attention/MLP ağırlıklarına uygulanır — bias\'lar ve LayerNorm decay\'siz kalır. 2) <code>AdamW(optimizer_grouped_parameters, lr=2e-5)</code> kanonik ince ayar öğrenme oranıyla decoupled-weight-decay optimizer\'ı kurar. 3) <code>num_training_steps</code>, <code>GRADIENT_ACCUMULATION_STEPS</code>\'e bölünür; böylece scheduler mikro batch\'leri değil optimizer güncellemelerini sayar; <code>num_warmup_steps</code> bu toplamın %6\'sıdır. 4) <code>get_linear_schedule_with_warmup(optimizer, ...)</code> doğrusal warmup + doğrusal decay çizelgesi üretir ve <code>model.to(device)</code> eğitim başlamadan önce ağı GPU\'ya taşır.</p>'

+ '<h4 class="l-subsection-title">6b — Gradient Accumulation ile Eğitim Döngüsü</h4>'
+ '<div class="code-wrap"><div class="code-label"><span>PYTHON (DEMO)</span> Training Loop with Gradient Accumulation <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="kw">from</span> torch.amp <span class="kw">import</span> autocast, GradScaler  <span class="cm"># modern: torch.amp (torch.cuda.amp deprecated)</span>\n'
+ 'scaler = <span class="fn">GradScaler</span>(<span class="str">"cuda"</span>)  <span class="cm"># Karma hassasiyet (fp16)</span>\n'
+ '\n'
+ 'best_f1 = <span class="num">0.0</span>\n'
+ 'global_step = <span class="num">0</span>\n'
+ '\n'
+ '<span class="kw">for</span> epoch <span class="kw">in</span> <span class="fn">range</span>(NUM_EPOCHS):\n'
+ '<span class="cm">    # ── Training phase ───────────────────────────────────────</span>\n'
+ '    model.<span class="fn">train</span>()\n'
+ '    total_train_loss = <span class="num">0.0</span>\n'
+ '    optimizer.<span class="fn">zero_grad</span>()\n'
+ '\n'
+ '    progress_bar = <span class="fn">tqdm</span>(train_loader, desc=<span class="str">f"Epoch {epoch+1}/{NUM_EPOCHS} [Train]"</span>)\n'
+ '    <span class="kw">for</span> step, batch <span class="kw">in</span> <span class="fn">enumerate</span>(progress_bar):\n'
+ '        batch = {k: v.<span class="fn">to</span>(device) <span class="kw">for</span> k, v <span class="kw">in</span> batch.<span class="fn">items</span>()}\n'
+ '\n'
+ '<span class="cm">        # Forward pass in fp16</span>\n'
+ '        <span class="kw">with</span> <span class="fn">autocast</span>(<span class="str">"cuda"</span>):\n'
+ '            outputs = <span class="fn">model</span>(**batch)\n'
+ '            loss = outputs.loss\n'
+ '<span class="cm">            # Normalize loss by accumulation steps</span>\n'
+ '            loss = loss / GRADIENT_ACCUMULATION_STEPS\n'
+ '\n'
+ '<span class="cm">        # Backward pass (scales gradient for fp16)</span>\n'
+ '        scaler.<span class="fn">scale</span>(loss).<span class="fn">backward</span>()\n'
+ '        total_train_loss += loss.<span class="fn">item</span>() * GRADIENT_ACCUMULATION_STEPS\n'
+ '\n'
+ '<span class="cm">        # Only update weights every GRADIENT_ACCUMULATION_STEPS steps</span>\n'
+ '        <span class="kw">if</span> (step + <span class="num">1</span>) % GRADIENT_ACCUMULATION_STEPS == <span class="num">0</span>:\n'
+ '<span class="cm">            # Unscale before clipping gradients</span>\n'
+ '            scaler.<span class="fn">unscale_</span>(optimizer)\n'
+ '<span class="cm">            # Gradient clipping prevents exploding gradients</span>\n'
+ '            torch.nn.utils.<span class="fn">clip_grad_norm_</span>(model.<span class="fn">parameters</span>(), max_norm=<span class="num">1.0</span>)\n'
+ '\n'
+ '            scaler.<span class="fn">step</span>(optimizer)      <span class="cm"># Update weights</span>\n'
+ '            scaler.<span class="fn">update</span>()             <span class="cm"># Update fp16 scale factor</span>\n'
+ '            scheduler.<span class="fn">step</span>()            <span class="cm"># Update LR</span>\n'
+ '            optimizer.<span class="fn">zero_grad</span>()       <span class="cm"># Reset gradients</span>\n'
+ '            global_step += <span class="num">1</span>\n'
+ '\n'
+ '        current_lr = scheduler.<span class="fn">get_last_lr</span>()[<span class="num">0</span>]\n'
+ '        progress_bar.<span class="fn">set_postfix</span>(loss=<span class="str">f"{loss.item()*GRADIENT_ACCUMULATION_STEPS:.4f}"</span>,\n'
+ '                                  lr=<span class="str">f"{current_lr:.2e}"</span>)\n'
+ '\n'
+ '    avg_train_loss = total_train_loss / <span class="fn">len</span>(train_loader)\n'
+ '\n'
+ '<span class="cm">    # ── Validation phase ─────────────────────────────────────</span>\n'
+ '    model.<span class="fn">eval</span>()\n'
+ '    all_preds, all_labels = [], []\n'
+ '\n'
+ '    <span class="kw">with</span> torch.<span class="fn">no_grad</span>():\n'
+ '        <span class="kw">for</span> batch <span class="kw">in</span> <span class="fn">tqdm</span>(val_loader, desc=<span class="str">f"Epoch {epoch+1}/{NUM_EPOCHS} [Val]"</span>):\n'
+ '            batch = {k: v.<span class="fn">to</span>(device) <span class="kw">for</span> k, v <span class="kw">in</span> batch.<span class="fn">items</span>()}\n'
+ '            <span class="kw">with</span> <span class="fn">autocast</span>(<span class="str">"cuda"</span>):\n'
+ '                outputs = <span class="fn">model</span>(**batch)\n'
+ '            logits = outputs.logits.<span class="fn">float</span>()  <span class="cm"># Cast back to fp32</span>\n'
+ '            preds  = torch.<span class="fn">argmax</span>(logits, dim=-<span class="num">1</span>)\n'
+ '            all_preds.<span class="fn">extend</span>(preds.<span class="fn">cpu</span>().<span class="fn">numpy</span>())\n'
+ '            all_labels.<span class="fn">extend</span>(batch[<span class="str">"labels"</span>].<span class="fn">cpu</span>().<span class="fn">numpy</span>())\n'
+ '\n'
+ '    all_preds  = np.<span class="fn">array</span>(all_preds)\n'
+ '    all_labels = np.<span class="fn">array</span>(all_labels)\n'
+ '    epoch_f1  = <span class="fn">f1_score</span>(all_labels, all_preds, average=<span class="str">"binary"</span>)\n'
+ '    epoch_acc = <span class="fn">accuracy_score</span>(all_labels, all_preds)\n'
+ '\n'
+ '    <span class="fn">print</span>(<span class="str">f"\</span>\nEpoch {epoch+<span class="num">1</span>}: loss={avg_train_loss:.4f}  <span class="str">"</span>\n'
+ '          <span class="str">f"val_acc={epoch_acc:.4f}  val_f1={epoch_f1:.4f}"</span>)\n'
+ '\n'
+ '<span class="cm">    # Save best model</span>\n'
+ '    <span class="kw">if</span> epoch_f1 > best_f1:\n'
+ '        best_f1 = epoch_f1\n'
+ '        model.<span class="fn">save_pretrained</span>(<span class="str">"./best-bert-sentiment"</span>)\n'
+ '        tokenizer.<span class="fn">save_pretrained</span>(<span class="str">"./best-bert-sentiment"</span>)\n'
+ '        <span class="fn">print</span>(<span class="str">f"  New best model saved! F1={best_f1:.4f}"</span>)\n'
+ '\n'
+ '<span class="fn">print</span>(<span class="str">f"\</span>\nTraining complete. Best validation F1: {best_f1:.4f}<span class="str">")</span>\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>Manuel eğitim döngüsünün adım başına yaptığı iş:</strong> 1) <code>autocast("cuda")</code> ileri geçişi fp16\'da çalıştırır ve <code>loss / GRADIENT_ACCUMULATION_STEPS</code> mikro batch başına kaybı normalize eder; böylece biriken gradyanlar sanal batch boyutuyla uyumlu olur. 2) <code>scaler.scale(loss).backward()</code> fp16 underflow\'unu önlemek için kaybı geri yayımdan önce ölçekler. 3) Her <code>GRADIENT_ACCUMULATION_STEPS</code>\'te unscale yapar, exploding gradient\'leri dizginlemek için <code>torch.nn.utils.clip_grad_norm_(..., max_norm=1.0)</code> çağırır, ardından <code>scaler.step(optimizer)</code> + <code>scheduler.step()</code> + <code>optimizer.zero_grad()</code> çalıştırır. 4) Doğrulama döngüsü <code>torch.no_grad()</code> + <code>argmax</code> + <code>f1_score</code> kullanır; <code>best_f1</code>\'i geçen her epoch <code>model.save_pretrained("./best-bert-sentiment")</code> ve eşleşen tokenizer kaydını tetikler.</p>'

/* ── 7. Hyperparameter Search ───────────────────────────── */
+ '<h3 class="l-section-title">Adım 7 — Optuna ile Hiperparametre Arama</h3>'
+ '<p class="l-text">Manuel hiperparametre ayarı yavaş ve güvenilmezdir. Trainer, otomatik hiperparametre araması için <strong>Optuna</strong> (ve Ray Tune / SigOpt) ile entegre olur. Bu özellikle üretim çalışmaları için değerlidir: küçük bir veri kümesinde bir kez arama yapın, en iyi yapılandırmayı bulun, ardından nihai modeli tam veri kümesinde eğitin.</p>'

+ '<div class="code-wrap"><div class="code-label"><span>PYTHON</span> Hyperparameter Search with Optuna <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="cm"># pip install optuna</span>\n'
+ '<span class="kw">import</span> optuna\n'
+ '\n'
+ '<span class="kw">def</span> <span class="fn">model_init</span>():\n'
+ '    <span class="str">"""Return a fresh (untrained) model — called before each trial."""</span>\n'
+ '    <span class="kw">return</span> AutoModelForSequenceClassification.<span class="fn">from_pretrained</span>(\n'
+ '        MODEL_NAME,\n'
+ '        num_labels=NUM_LABELS,\n'
+ '        id2label=id2label,\n'
+ '        label2id=label2id,\n'
+ '    )\n'
+ '\n'
+ '<span class="kw">def</span> <span class="fn">optuna_hp_space</span>(trial):\n'
+ '    <span class="str">"""Define the search space for Optuna trials."""</span>\n'
+ '    <span class="kw">return</span> {\n'
+ '        <span class="str">"learning_rate"</span>:              trial.<span class="fn">suggest_float</span>(<span class="str">"learning_rate"</span>, <span class="num">1e-5</span>, <span class="num">5e-5</span>, log=<span class="kw">True</span>),\n'
+ '        <span class="str">"num_train_epochs"</span>:           trial.<span class="fn">suggest_int</span>(<span class="str">"num_train_epochs"</span>, <span class="num">2</span>, <span class="num">4</span>),\n'
+ '        <span class="str">"per_device_train_batch_size"</span>:trial.<span class="fn">suggest_categorical</span>(<span class="str">"per_device_train_batch_size"</span>, [<span class="num">8</span>, <span class="num">16</span>, <span class="num">32</span>]),\n'
+ '        <span class="str">"warmup_ratio"</span>:               trial.<span class="fn">suggest_float</span>(<span class="str">"warmup_ratio"</span>, <span class="num">0.0</span>, <span class="num">0.15</span>),\n'
+ '        <span class="str">"weight_decay"</span>:               trial.<span class="fn">suggest_float</span>(<span class="str">"weight_decay"</span>, <span class="num">0.0</span>, <span class="num">0.1</span>),\n'
+ '    }\n'
+ '\n'
+ '<span class="cm"># Create a Trainer with model_init instead of model</span>\n'
+ 'hp_trainer = <span class="fn">Trainer</span>(\n'
+ '    model_init=model_init,   <span class="cm"># NOT model=model</span>\n'
+ '    args=training_args,\n'
+ '    train_dataset=tokenized_datasets[<span class="str">"train"</span>],\n'
+ '    eval_dataset=tokenized_datasets[<span class="str">"validation"</span>],\n'
+ '    tokenizer=tokenizer,\n'
+ '    data_collator=data_collator,\n'
+ '    compute_metrics=compute_metrics,\n'
+ ')\n'
+ '\n'
+ '<span class="cm"># Run hyperparameter search — 10 trials, optimize for F1</span>\n'
+ 'best_run = hp_trainer.<span class="fn">hyperparameter_search</span>(\n'
+ '    n_trials=<span class="num">10</span>,\n'
+ '    direction=<span class="str">"maximize"</span>,\n'
+ '    hp_space=optuna_hp_space,\n'
+ '    backend=<span class="str">"optuna"</span>,\n'
+ ')\n'
+ '\n'
+ '<span class="fn">print</span>(<span class="str">"Best hyperparameters:"</span>)\n'
+ '<span class="kw">for</span> k, v <span class="kw">in</span> best_run.hyperparameters.<span class="fn">items</span>():\n'
+ '    <span class="fn">print</span>(<span class="str">f"  {k}: {v}"</span>)\n'
+ '<span class="cm"># Best hyperparameters:</span>\n'
+ '<span class="cm">#   learning_rate: 2.34e-05</span>\n'
+ '<span class="cm">#   num_train_epochs: 3</span>\n'
+ '<span class="cm">#   per_device_train_batch_size: 16</span>\n'
+ '<span class="cm">#   warmup_ratio: 0.062</span>\n'
+ '<span class="cm">#   weight_decay: 0.011</span>\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>Optuna aramasının nasıl bağlandığı:</strong> 1) <code>model_init()</code> her denemede taze bir <code>AutoModelForSequenceClassification</code> döndürür — Trainer\'ın tek bir modele değil bir callable\'a ihtiyacı vardır çünkü her deneme sıfırdan başlar. 2) <code>optuna_hp_space(trial)</code> arama aralıklarını öğrenme oranı için <code>trial.suggest_float(..., log=True)</code>, epoch\'lar için <code>suggest_int</code>, batch boyutu için <code>suggest_categorical</code> ile bildirir. 3) <code>Trainer(model_init=model_init, ...)</code> yapıcısı her zamanki <code>model=</code> argümanını factory ile değiştirir. 4) <code>hp_trainer.hyperparameter_search(n_trials=10, direction="maximize", hp_space=optuna_hp_space, backend="optuna")</code> 10 deneme çalıştırır; her biri <code>compute_metrics</code>\'in F1\'ini maksimize eder ve kazanan yapılandırmayla <code>best_run.hyperparameters</code>\'i döner.</p>'

+ '<h4 class="l-subsection-title">BERT Fine-Tuning için Temel Hiperparametreler</h4>'
+ '<div class="calc-cards">'
+ '<div class="calc-card">'
+ '<div class="card-title">Learning Rate</div>'
+ '<div class="card-body">Aralık: <strong>1e-5 ile 5e-5</strong>. En hassas hiperparametre. Çok yüksek (örn. 1e-3) önceden eğitilmiş ağırlıkların yıkıcı biçimde unutulmasına neden olur. Çok düşük (&lt;1e-5) model neredeyse güncellenmez. bert-base için 2e-5\'ten başlayın.</div>'
+ '</div>'
+ '<div class="calc-card">'
