+ '<p class="l-text"><strong>Değerlendirme bloğu ne üretiyor:</strong> 1) <code>trainer.evaluate(tokenized_datasets["test"])</code> değerlendirme döngüsünü test bölümünde yeniden kullanır ve <code>eval_loss</code>, <code>eval_accuracy</code>, <code>eval_f1</code>, <code>eval_precision</code>, <code>eval_recall</code> içeren bir sözlük döner. 2) <code>trainer.predict(...)</code> ham <code>predictions</code> (logits) ve <code>label_ids</code>\'i döndürür; <code>np.argmax(logits, axis=-1)</code> bunları sert sınıf etiketlerine çevirir. 3) sklearn\'den <code>classification_report</code> sınıf başına precision, recall, F1 ile makro ve ağırlıklı ortalamaları yazdırır. 4) <code>confusion_matrix</code> + <code>sns.heatmap</code> false positive\'leri false negative\'lerle karşılaştırır — yazdırılan matris 25.000 örnek üzerinden ~923 FP ve ~796 FN gösterir.</p>'

