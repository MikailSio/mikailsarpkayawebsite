+ 'no_decay = [<span class="str">"bias"</span>, <span class="str">"LayerNorm.weight"</span>]\n'
+ 'optimizer_grouped_parameters = [\n'
+ '    {\n'
+ '        <span class="str">"params"</span>: [p <span class="kw">for</span> n, p <span class="kw">in</span> model.<span class="fn">named_parameters</span>()\n'
+ '                   <span class="kw">if</span> <span class="kw">not</span> <span class="fn">any</span>(nd <span class="kw">in</span> n <span class="kw">for</span> nd <span class="kw">in</span> no_decay)],\n'
+ '        <span class="str">"weight_decay"</span>: <span class="num">0.01</span>,\n'
+ '    },\n'
+ '    {\n'
+ '        <span class="str">"params"</span>: [p <span class="kw">for</span> n, p <span class="kw">in</span> model.<span class="fn">named_parameters</span>()\n'
+ '                   <span class="kw">if</span> <span class="fn">any</span>(nd <span class="kw">in</span> n <span class="kw">for</span> nd <span class="kw">in</span> no_decay)],\n'
+ '        <span class="str">"weight_decay"</span>: <span class="num">0.0</span>,   <span class="cm"># No decay on biases and LayerNorm</span>\n'
+ '    },\n'
+ ']\n'
+ 'optimizer = <span class="fn">AdamW</span>(optimizer_grouped_parameters, lr=<span class="num">2e-5</span>)\n'
+ '\n'
+ '<span class="cm"># ── Learning rate scheduler ──────────────────────────────────</span>\n'
+ 'NUM_EPOCHS = <span class="num">3</span>\n'
+ 'GRADIENT_ACCUMULATION_STEPS = <span class="num">2</span>\n'
+ 'num_training_steps = (<span class="fn">len</span>(train_loader) // GRADIENT_ACCUMULATION_STEPS) * NUM_EPOCHS\n'
+ 'num_warmup_steps   = <span class="fn">int</span>(<span class="num">0.06</span> * num_training_steps)   <span class="cm"># 6% warmup</span>\n'
+ '\n'
+ 'scheduler = <span class="fn">get_linear_schedule_with_warmup</span>(\n'
+ '    optimizer,\n'
+ '    num_warmup_steps=num_warmup_steps,\n'
+ '    num_training_steps=num_training_steps,\n'
+ ')\n'
+ '\n'
+ 'model.<span class="fn">to</span>(device)\n'
+ '<span class="fn">print</span>(<span class="str">f"Training steps: {num_training_steps}, Warmup steps: {num_warmup_steps}"</span>)\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>How the optimizer and scheduler are set up by hand:</strong> 1) The <code>no_decay</code> list (<code>["bias", "LayerNorm.weight"]</code>) splits parameters into two groups so weight decay applies only to attention/MLP weights — biases and LayerNorm stay decay-free. 2) <code>AdamW(optimizer_grouped_parameters, lr=2e-5)</code> builds the decoupled-weight-decay optimizer with the canonical fine-tuning learning rate. 3) <code>num_training_steps</code> divides by <code>GRADIENT_ACCUMULATION_STEPS</code> so the scheduler counts optimizer updates, not micro-batches; <code>num_warmup_steps</code> is 6% of that total. 4) <code>get_linear_schedule_with_warmup(optimizer, ...)</code> produces a linear warm-up + linear decay schedule and <code>model.to(device)</code> moves the network to GPU before training starts.</p>'

/* Training loop */
+ '<h4 class="l-subsection-title">6b — Training Loop with Gradient Accumulation</h4>'
+ '<div class="code-wrap"><div class="code-label"><span>PYTHON (DEMO)</span> Training Loop with Gradient Accumulation <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="kw">from</span> torch.amp <span class="kw">import</span> autocast, GradScaler  <span class="cm"># modern: torch.amp (torch.cuda.amp deprecated)</span>\n'
+ 'scaler = <span class="fn">GradScaler</span>(<span class="str">"cuda"</span>)  <span class="cm"># Karma hassasiyet (fp16)</span>\n'
+ '\n'
+ 'best_f1 = <span class="num">0.0</span>\n'
+ 'global_step = <span class="num">0</span>\n'
+ '\n'
+ '<span class="kw">for</span> epoch <span class="kw">in</span> <span class="fn">range</span>(NUM_EPOCHS):\n'
+ '<span class="cm">    # ── Training phase ───────────────────────────────────────</span>\n'
+ '    model.<span class="fn">train</span>()\n'
+ '    total_train_loss = <span class="num">0.0</span>\n'
+ '    optimizer.<span class="fn">zero_grad</span>()\n'
+ '\n'
+ '    progress_bar = <span class="fn">tqdm</span>(train_loader, desc=<span class="str">f"Epoch {epoch+1}/{NUM_EPOCHS} [Train]"</span>)\n'
+ '    <span class="kw">for</span> step, batch <span class="kw">in</span> <span class="fn">enumerate</span>(progress_bar):\n'
+ '        batch = {k: v.<span class="fn">to</span>(device) <span class="kw">for</span> k, v <span class="kw">in</span> batch.<span class="fn">items</span>()}\n'
+ '\n'
+ '<span class="cm">        # Forward pass in fp16</span>\n'
+ '        <span class="kw">with</span> <span class="fn">autocast</span>(<span class="str">"cuda"</span>):\n'
+ '            outputs = <span class="fn">model</span>(**batch)\n'
+ '            loss = outputs.loss\n'
+ '<span class="cm">            # Normalize loss by accumulation steps</span>\n'
+ '            loss = loss / GRADIENT_ACCUMULATION_STEPS\n'
+ '\n'
+ '<span class="cm">        # Backward pass (scales gradient for fp16)</span>\n'
+ '        scaler.<span class="fn">scale</span>(loss).<span class="fn">backward</span>()\n'
+ '        total_train_loss += loss.<span class="fn">item</span>() * GRADIENT_ACCUMULATION_STEPS\n'
+ '\n'
+ '<span class="cm">        # Only update weights every GRADIENT_ACCUMULATION_STEPS steps</span>\n'
+ '        <span class="kw">if</span> (step + <span class="num">1</span>) % GRADIENT_ACCUMULATION_STEPS == <span class="num">0</span>:\n'
+ '<span class="cm">            # Unscale before clipping gradients</span>\n'
+ '            scaler.<span class="fn">unscale_</span>(optimizer)\n'
+ '<span class="cm">            # Gradient clipping prevents exploding gradients</span>\n'
+ '            torch.nn.utils.<span class="fn">clip_grad_norm_</span>(model.<span class="fn">parameters</span>(), max_norm=<span class="num">1.0</span>)\n'
+ '\n'
+ '            scaler.<span class="fn">step</span>(optimizer)      <span class="cm"># Update weights</span>\n'
+ '            scaler.<span class="fn">update</span>()             <span class="cm"># Update fp16 scale factor</span>\n'
+ '            scheduler.<span class="fn">step</span>()            <span class="cm"># Update LR</span>\n'
+ '            optimizer.<span class="fn">zero_grad</span>()       <span class="cm"># Reset gradients</span>\n'
+ '            global_step += <span class="num">1</span>\n'
+ '\n'
+ '        current_lr = scheduler.<span class="fn">get_last_lr</span>()[<span class="num">0</span>]\n'
+ '        progress_bar.<span class="fn">set_postfix</span>(loss=<span class="str">f"{loss.item()*GRADIENT_ACCUMULATION_STEPS:.4f}"</span>,\n'
+ '                                  lr=<span class="str">f"{current_lr:.2e}"</span>)\n'
+ '\n'
+ '    avg_train_loss = total_train_loss / <span class="fn">len</span>(train_loader)\n'
+ '\n'
+ '<span class="cm">    # ── Validation phase ─────────────────────────────────────</span>\n'
+ '    model.<span class="fn">eval</span>()\n'
+ '    all_preds, all_labels = [], []\n'
+ '\n'
+ '    <span class="kw">with</span> torch.<span class="fn">no_grad</span>():\n'
+ '        <span class="kw">for</span> batch <span class="kw">in</span> <span class="fn">tqdm</span>(val_loader, desc=<span class="str">f"Epoch {epoch+1}/{NUM_EPOCHS} [Val]"</span>):\n'
+ '            batch = {k: v.<span class="fn">to</span>(device) <span class="kw">for</span> k, v <span class="kw">in</span> batch.<span class="fn">items</span>()}\n'
+ '            <span class="kw">with</span> <span class="fn">autocast</span>(<span class="str">"cuda"</span>):\n'
+ '                outputs = <span class="fn">model</span>(**batch)\n'
+ '            logits = outputs.logits.<span class="fn">float</span>()  <span class="cm"># Cast back to fp32</span>\n'
+ '            preds  = torch.<span class="fn">argmax</span>(logits, dim=-<span class="num">1</span>)\n'
+ '            all_preds.<span class="fn">extend</span>(preds.<span class="fn">cpu</span>().<span class="fn">numpy</span>())\n'
+ '            all_labels.<span class="fn">extend</span>(batch[<span class="str">"labels"</span>].<span class="fn">cpu</span>().<span class="fn">numpy</span>())\n'
+ '\n'
+ '    all_preds  = np.<span class="fn">array</span>(all_preds)\n'
+ '    all_labels = np.<span class="fn">array</span>(all_labels)\n'
+ '    epoch_f1  = <span class="fn">f1_score</span>(all_labels, all_preds, average=<span class="str">"binary"</span>)\n'
+ '    epoch_acc = <span class="fn">accuracy_score</span>(all_labels, all_preds)\n'
+ '\n'
+ '    <span class="fn">print</span>(<span class="str">f"\</span>\nEpoch {epoch+<span class="num">1</span>}: loss={avg_train_loss:.4f}  <span class="str">"</span>\n'
+ '          <span class="str">f"val_acc={epoch_acc:.4f}  val_f1={epoch_f1:.4f}"</span>)\n'
+ '\n'
+ '<span class="cm">    # Save best model</span>\n'
+ '    <span class="kw">if</span> epoch_f1 > best_f1:\n'
+ '        best_f1 = epoch_f1\n'
+ '        model.<span class="fn">save_pretrained</span>(<span class="str">"./best-bert-sentiment"</span>)\n'
+ '        tokenizer.<span class="fn">save_pretrained</span>(<span class="str">"./best-bert-sentiment"</span>)\n'
+ '        <span class="fn">print</span>(<span class="str">f"  New best model saved! F1={best_f1:.4f}"</span>)\n'
+ '\n'
+ '<span class="fn">print</span>(<span class="str">f"\</span>\nTraining complete. Best validation F1: {best_f1:.4f}<span class="str">")</span>\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong>What the manual training loop is doing per step:</strong> 1) <code>autocast("cuda")</code> runs the forward pass in fp16 and <code>loss / GRADIENT_ACCUMULATION_STEPS</code> normalizes the per-micro-batch loss so accumulated gradients match a virtual batch size. 2) <code>scaler.scale(loss).backward()</code> scales the loss before backprop to prevent fp16 underflow. 3) Every <code>GRADIENT_ACCUMULATION_STEPS</code> we unscale, run <code>torch.nn.utils.clip_grad_norm_(..., max_norm=1.0)</code> to tame exploding gradients, then call <code>scaler.step(optimizer)</code> + <code>scheduler.step()</code> + <code>optimizer.zero_grad()</code>. 4) The validation loop uses <code>torch.no_grad()</code> + <code>argmax</code> + <code>f1_score</code>, and any epoch that beats <code>best_f1</code> triggers <code>model.save_pretrained("./best-bert-sentiment")</code> + the matching tokenizer save.</p>'

