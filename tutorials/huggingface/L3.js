+ '<h4 class="l-subsection-title">4b — compute_metrics: Accuracy, F1, Precision, Recall</h4>'
+ '<div class="code-wrap"><div class="code-label"><span>PYTHON (DEMO)</span> compute_metrics &mdash; Evaluation Metrics <button class="code-copy">COPY</button></div><div class="code-block"><pre><code>'
+ '<span class="kw">import</span> numpy <span class="kw">as</span> np\n'
+ '<span class="kw">import</span> evaluate  <span class="cm"># modern: pip install evaluate (load_metric kaldırıldı)</span>\n'
+ '<span class="kw">from</span> sklearn.metrics <span class="kw">import</span> f1_score, precision_score, recall_score, accuracy_score\n'
+ '\n'
+ '<span class="kw">def</span> <span class="fn">compute_metrics</span>(eval_pred):\n'
+ '    <span class="str">"""</span>\n'
+ '    Called by Trainer after each evaluation <span class="kw">pass</span>.\n'
+ '    eval_pred <span class="kw">is</span> a namedtuple: (logits, labels)\n'
+ '    logits shape: (num_examples, num_labels)\n'
+ '    labels shape: (num_examples,)\n'
+ '    <span class="str">"""</span>\n'
+ '    logits, labels = eval_pred\n'
+ '\n'
+ '<span class="cm">    # Convert logits → predicted class index</span>\n'
+ '    predictions = np.<span class="fn">argmax</span>(logits, axis=-<span class="num">1</span>)\n'
+ '\n'
+ '<span class="cm">    # Compute all metrics</span>\n'
+ '    acc = <span class="fn">accuracy_score</span>(labels, predictions)\n'
+ '    f1  = <span class="fn">f1_score</span>(labels, predictions, average=<span class="str">"binary"</span>)\n'
+ '    prec = <span class="fn">precision_score</span>(labels, predictions, average=<span class="str">"binary"</span>)\n'
+ '    rec  = <span class="fn">recall_score</span>(labels, predictions, average=<span class="str">"binary"</span>)\n'
+ '\n'
+ '    <span class="kw">return</span> {\n'
+ '        <span class="str">"accuracy"</span>:  <span class="fn">round</span>(acc,  <span class="num">4</span>),\n'
+ '        <span class="str">"f1"</span>:        <span class="fn">round</span>(f1,   <span class="num">4</span>),\n'
+ '        <span class="str">"precision"</span>: <span class="fn">round</span>(prec, <span class="num">4</span>),\n'
+ '        <span class="str">"recall"</span>:    <span class="fn">round</span>(rec,  <span class="num">4</span>),\n'
+ '    }\n'
+ '\n'
+ '<span class="cm"># For multi-class (e.g., 3-way sentiment: neg/neu/pos):</span>\n'
+ '<span class="cm"># f1 = f1_score(labels, predictions, average="weighted")</span>\n'
+ '<span class="cm"># This weights F1 by class frequency — appropriate for imbalanced datasets</span>\n'
+ '</code></pre></div></div>'
+ '<p class="l-text"><strong><code>compute_metrics</code> her değerlendirme geçişinde ne yapar:</strong> 1) Trainer, her değerlendirme adımından sonra fonksiyonu bir <code>EvalPrediction</code> namedtuple\'ı <code>(logits, labels)</code> ile çağırır. 2) <code>np.argmax(logits, axis=-1)</code> logits\'i ayrık sınıf tahminlerine indirger. 3) sklearn\'den <code>accuracy_score</code>, <code>f1_score</code>, <code>precision_score</code>, <code>recall_score</code> dört standart ikili sınıflandırma metriğini üretir. 4) Döndürdüğünüz sözlük Trainer loglarında görünür ve (<code>metric_for_best_model="f1"</code> ile birleşince) en iyi checkpoint seçimini yönetir. Çok sınıflı problemlerde <code>average="binary"</code>\'i <code>average="weighted"</code> ile değiştirerek metrikleri sınıf frekansına göre ağırlıklandırın.</p>'

